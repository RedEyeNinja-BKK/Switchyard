"""The capability contract's judgement, tested without a build.

The contract has two halves that can fail independently: the INVENTORY (what the
artifact actually contains) and the COMPARISON (does the candidate still provide
what the deployed release provides). The inventory needs a real binary and source
tree, so it is exercised against the tree in CI. The comparison needs neither, and
it is the half that a self-consistent but incomplete manifest defeats -- which is
the failure this gate exists for.

So these tests build manifests in memory and assert the verdict. The negative
control is the important one: a manifest that is perfectly valid on its own terms,
generated by the tool itself, listing every family it has -- and missing
economics -- must still be rejected against the deployed baseline.
"""

import hashlib
import json
import os
import subprocess
import sys

import pytest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TOOL = os.path.join(ROOT, "scripts", "release", "capability_contract.py")
CONTRACT = os.path.join(ROOT, "scripts", "release", "capabilities.toml")

sys.path.insert(0, os.path.join(ROOT, "scripts", "release"))
import capability_contract as cc  # noqa: E402


def manifest(families, *, commit="a" * 40, sha="0" * 64, sparse=(), event_driven=(),
             subsystems=None):
    """A minimal capability manifest with the shape the tool produces.

    Families are always_present unless named in `event_driven`, so the preflight
    literal check has something to require by default.
    """
    fams = {}
    groups = {}
    for family in families:
        subsystem = (subsystems or {}).get(family, "core")
        fams[family] = {
            "instrument": family.replace("_total", "").replace("_", "."),
            "kind": "counter",
            "kind_basis": "source",
            "subsystem": subsystem,
            "class": "event_driven" if family in event_driven else "always_present",
        }
        groups.setdefault(subsystem, []).append(family)
    return {
        "contract_version": 1,
        "build": {"commit": commit, "binary_sha256": sha, "binary_bytes": 1},
        "subsystems": groups,
        "families": fams,
        "sparse_families": [f for f in families if f in sparse],
        "not_compiled": [],
    }


def literal(family):
    return family.replace("_total", "").replace("_", ".")


def write(tmp_path, name, data):
    path = tmp_path / name
    path.write_text(json.dumps(data))
    return str(path)


def binary_with(tmp_path, families, extra=b""):
    body = " ".join(literal(f) for f in families).encode() + extra
    path = tmp_path / "switchyard-server"
    path.write_bytes(body)
    return str(path), hashlib.sha256(body).hexdigest()


DEPLOYED = [
    "switchyard_build_info",
    "switchyard_economics_account_fetch_total",
    "switchyard_economics_provider_balance",
    "switchyard_economics_rolling_tokens",
    "switchyard_llm_calls_total",
    "switchyard_upstream_attempts_total",
]


