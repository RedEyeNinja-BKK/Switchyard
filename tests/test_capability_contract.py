def test_identical_candidate_passes(tmp_path):
    base = write(tmp_path, "base.json", manifest(DEPLOYED))
    cand = write(tmp_path, "cand.json", manifest(DEPLOYED))
    assert cc.main(["validate", "--candidate", cand, "--baseline", base]) == 0


def test_a_self_consistent_manifest_that_omits_economics_is_rejected(tmp_path):
    """The 2026-10-27 failure, as a test.

    The candidate's manifest is internally perfect: the tool generated it from a
    real build, it lists every family that build contains, and nothing in it is
    stale or unclassified. It is still incomplete, and completeness cannot be
    established from the candidate alone -- which is exactly why the comparison
    uses the deployed baseline.
    """
    base = write(tmp_path, "base.json", manifest(DEPLOYED))
    economics_free = [f for f in DEPLOYED if "economics" not in f]
    cand = write(tmp_path, "cand.json", manifest(economics_free))
    rc = cc.main(["validate", "--candidate", cand, "--baseline", base])
    assert rc == cc.EXIT_REMOVAL


def test_losing_a_whole_subsystem_is_a_removal_even_when_each_family_is_approved(tmp_path):
    """Approving families one by one must not license dropping the subsystem."""
    groups = {f: ("economics" if "economics" in f else "core") for f in DEPLOYED}
    base = write(tmp_path, "base.json", manifest(DEPLOYED, subsystems=groups))
    economics_free = [f for f in DEPLOYED if "economics" not in f]
    cand = write(tmp_path, "cand.json", manifest(economics_free, subsystems=groups))
    approvals = tmp_path / "approvals.json"
    approvals.write_text(json.dumps({"removed": {
        "switchyard_economics_account_fetch_total": "reviewed",
        "switchyard_economics_provider_balance": "reviewed",
        "switchyard_economics_rolling_tokens": "reviewed",
    }}))
    assert cc.main(["validate", "--candidate", cand, "--baseline", base,
                    "--approvals", str(approvals)]) == cc.EXIT_REMOVAL


def test_an_approved_removal_passes_and_an_unapproved_one_does_not(tmp_path):
    base = write(tmp_path, "base.json", manifest(DEPLOYED))
    cand = write(tmp_path, "cand.json", manifest(DEPLOYED[:5]))
    approvals = tmp_path / "approvals.json"
    approvals.write_text(json.dumps(
        {"removed": {"switchyard_upstream_attempts_total": "provider retired"}}))
    assert cc.main(["validate", "--candidate", cand, "--baseline", base,
                    "--approvals", str(approvals)]) == 0

    approvals.write_text(json.dumps(
        {"removed": {"switchyard_llm_calls_total": "reviewed"}}))
    assert cc.main(["validate", "--candidate", cand, "--baseline", base,
                    "--approvals", str(approvals)]) == cc.EXIT_REMOVAL


def test_a_family_that_moves_subsystem_is_reported(tmp_path, capsys):
    """Reclassification is a contract change, even with every family preserved.

    The family set and the subsystem set are both unchanged here -- `llm` keeps
    a member in each manifest -- so the only thing that differs is which
    subsystem one family belongs to. Attribution depends on that mapping, so a
    silent move corrupts every per-subsystem total without any family appearing
    or disappearing.
    """
    base = write(tmp_path, "base.json", manifest(
        DEPLOYED,
        subsystems={"switchyard_llm_calls_total": "llm",
                    "switchyard_upstream_attempts_total": "llm"}))
    cand = write(tmp_path, "cand.json", manifest(
        DEPLOYED,
        subsystems={"switchyard_upstream_attempts_total": "llm"}))
    rc = cc.main(["validate", "--candidate", cand, "--baseline", base])
    out = capsys.readouterr().out
    assert rc != 0
    assert "changed" in out and "subsystem" in out, out


def test_a_new_capability_is_reported_but_not_blocked(tmp_path):
    base = write(tmp_path, "base.json", manifest(DEPLOYED))
    cand = write(tmp_path, "cand.json", manifest(DEPLOYED + ["switchyard_new_thing_total"]))
    assert cc.main(["validate", "--candidate", cand, "--baseline", base]) == 0


