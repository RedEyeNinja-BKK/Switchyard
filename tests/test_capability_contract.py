def test_the_checked_in_contract_loads_and_is_internally_consistent():
    data = cc.load_contract(CONTRACT)
    families = data["families"]
    assert len(families) > 40, "the contract should describe the real surface"
    for name, entry in families.items():
        if entry["class"] == "event_driven":
            assert entry.get("trigger"), f"{name} has no deterministic trigger"
        if entry.get("sparse"):
            assert entry.get("reachability_test"), f"{name} is sparse with no proof"


def test_every_sparse_family_names_a_test_that_exists():
    """A reachability proof named but never written is a claim, not a proof."""
    data = cc.load_contract(CONTRACT)
    sources = []
    for dirpath, dirnames, filenames in os.walk(os.path.join(ROOT, "crates")):
        dirnames[:] = [d for d in dirnames if d not in ("target", "tests")]
        sources.extend(os.path.join(dirpath, f) for f in filenames if f.endswith(".rs"))
    text = "\n".join(open(p, encoding="utf-8", errors="replace").read() for p in sources)

    sparse = {n: e for n, e in data["families"].items() if e.get("sparse")}
    assert sparse, "no sparse families declared; the reachability rule would be inert"
    for name, entry in sparse.items():
        function = entry["reachability_test"].rsplit("::", 1)[-1]
        assert function in text, f"{name}: {entry['reachability_test']} does not exist"


def test_a_declared_kind_must_be_a_real_instrument_constructor(tmp_path):
    path = tmp_path / "contract.toml"
    path.write_text(
        '[meta]\ncontract_version = 1\n\n'
        '[families."switchyard.x"]\n'
        'subsystem = "routing"\n'
        'class = "event_driven"\n'
        'trigger = "serve one request"\n'
        'kind = "counter"\n'
    )
    with pytest.raises(cc.ContractError) as excinfo:
        cc.load_contract(str(path))
    assert excinfo.value.code == cc.EXIT_CONTRACT


