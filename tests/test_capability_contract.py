def test_verify_live_fails_when_a_required_family_never_appears(tmp_path, monkeypatch):
    """The live check must fail on absence, not just report it.

    A restarted binary publishes a counter only once something observes it, so
    the check has a wait budget; but an always_present family that is still
    missing when the budget expires means the release is not exposing a
    capability the contract says it always has.
    """
    expo = "switchyard_build_info 1\nswitchyard_llm_calls_total 4\n"
    monkeypatch.setattr(cc, "fetch_exposition", lambda url, timeout=20: expo)
    path = write(tmp_path, "caps.json", manifest(DEPLOYED))
    assert cc.main(["verify-live", "--manifest", path, "--metrics-url", "http://x/metrics",
                    "--wait", "0", "--interval", "0"]) != 0


def test_verify_live_passes_when_the_required_families_are_present(tmp_path, monkeypatch):
    expo = "".join(f"{f} 1\n" for f in DEPLOYED)
    monkeypatch.setattr(cc, "fetch_exposition", lambda url, timeout=20: expo)
    path = write(tmp_path, "caps.json", manifest(DEPLOYED))
    assert cc.main(["verify-live", "--manifest", path, "--metrics-url", "http://x/metrics",
                    "--wait", "0", "--interval", "0"]) == 0


def test_the_tool_is_runnable_as_a_program():
    """The installer calls it as a process on a host with no checkout."""
    out = subprocess.run([sys.executable, TOOL, "--help"],
                         capture_output=True, text=True)
    assert out.returncode == 0
    for command in ("generate", "validate", "preflight", "verify-live"):
        assert command in out.stdout
