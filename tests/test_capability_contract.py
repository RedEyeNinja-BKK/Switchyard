def test_preflight_rejects_a_manifest_that_describes_another_binary(tmp_path):
    """A manifest is evidence only about the artifact it was generated beside."""
    base = write(tmp_path, "base.json", manifest(DEPLOYED))
    binary, _sha = binary_with(tmp_path, DEPLOYED)
    cand = write(tmp_path, "cand.json", manifest(DEPLOYED, sha="f" * 64))
    rc = cc.main(["preflight", "--binary", binary, "--manifest", cand,
                  "--baseline", base])
    assert rc == cc.EXIT_DRIFT


def test_preflight_rejects_an_artifact_missing_a_required_literal(tmp_path):
    """Caught even when the manifest claims the capability.

    The manifest is bound to the binary's hash, so it is about this artifact; the
    literal check then asks the bytes, not the manifest, whether the family can be
    constructed at all.
    """
    present = [f for f in DEPLOYED if f != "switchyard_economics_rolling_tokens"]
    binary, sha = binary_with(tmp_path, present)
    base = write(tmp_path, "base.json", manifest(DEPLOYED))
    cand = write(tmp_path, "cand.json", manifest(DEPLOYED, sha=sha))
    rc = cc.main(["preflight", "--binary", binary, "--manifest", cand,
                  "--baseline", base])
    assert rc == cc.EXIT_DRIFT


def test_preflight_requires_a_sparse_family_to_be_compiled_but_not_emitted(tmp_path):
    """A sparse family is required in the bytes and never in the exposition."""
    families = DEPLOYED + ["switchyard_composition_cross_total"]
    binary, sha = binary_with(tmp_path, [f for f in families
                                         if f != "switchyard_composition_cross_total"])
    base = write(tmp_path, "base.json",
                 manifest(families, sparse=["switchyard_composition_cross_total"],
                          event_driven=["switchyard_composition_cross_total"]))
    cand = write(tmp_path, "cand.json",
                 manifest(families, sha=sha, sparse=["switchyard_composition_cross_total"],
                          event_driven=["switchyard_composition_cross_total"]))
    assert cc.main(["preflight", "--binary", binary, "--manifest", cand,
                    "--baseline", base]) == cc.EXIT_DRIFT


def test_preflight_passes_when_identity_and_presence_are_sound(tmp_path):
    binary, sha = binary_with(tmp_path, DEPLOYED)
    base = write(tmp_path, "base.json", manifest(DEPLOYED))
    cand = write(tmp_path, "cand.json", manifest(DEPLOYED, sha=sha))
    assert cc.main(["preflight", "--binary", binary, "--manifest", cand,
                    "--baseline", base]) == 0


def test_preflight_still_applies_the_comparison(tmp_path):
    """Identity and presence passing is not enough: the baseline is still compared."""
    economics_free = [f for f in DEPLOYED if "economics" not in f]
    cand_binary, sha = binary_with(tmp_path, economics_free)
    base = write(tmp_path, "base.json", manifest(DEPLOYED))
    cand = write(tmp_path, "cand.json", manifest(economics_free, sha=sha))
    assert cc.main(["preflight", "--binary", cand_binary, "--manifest", cand,
                    "--baseline", base]) == cc.EXIT_DRIFT


